/*
Разница между var, 
let и const в JavaScript заключается в области видимости, 
возможности повторного объявления и изменяемости значения:

1. var
   - Область видимости: функциональная (function scope) или глобальная, если объявлена вне функции.
   - Можно объявлять повторно.
   - Значение можно изменять.
   - Подвержена "hoisting" (всплытию), 
     но инициализация происходит только в строке объявления.

2. let
   - Область видимости: блочная (block scope), то есть внутри { }.
   - Нельзя объявлять повторно в одной области видимости.
   - Значение можно изменять.
   - Также подвержен "hoisting", 
     но использовать переменную до объявления нельзя.

3. const
   - Область видимости: блочная (block scope).
   - Нельзя объявлять повторно и нельзя изменять значение (переменная — константа).
   - Значение должно быть присвоено сразу при объявлении.
   - Для объектов и массивов const запрещает только переназначение переменной, 
     но не изменение самого объекта или массива.
*/

var a = 1;
let b = 2;
const c = 3;

a = 10; // OK
b = 20; // OK
// c = 30; // Ошибка! Нельзя изменить значение const

/*
**Когда использовать:**
- Используйте let для изменяемых переменных внутри блока.
- Используйте const для переменных, которые не должны изменяться.
- var использовать не рекомендуется, кроме как для старых проектов.
*/

